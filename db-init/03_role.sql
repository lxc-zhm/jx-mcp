-- 受限角色：仅 DML，无 DDL —— 数据库层 DDL 防御的保底
-- 生产环境请改掉默认密码；若已 REVOKE PUBLIC 的 CONNECT，需另行授予
CREATE ROLE jx_mcp_app LOGIN PASSWORD 'jx_mcp_app';

GRANT USAGE ON SCHEMA public TO jx_mcp_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO jx_mcp_app;
-- SERIAL 主键的 INSERT 需要 NEXTVAL/CURRVAL
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO jx_mcp_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO jx_mcp_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO jx_mcp_app;
